/// Provides extension methods for validating nullable types and elevating them to non-nullable types
/// within expression pipelines.
///
/// This extension enables expressive, chainable null assertions without requiring imperative `if` checks.
/// It is utilized in architectural components like dependency injection (e.g., resolving an internal entry
/// from a map in [Pillar]) to ensure configuration integrity while throwing context-aware exceptions.
library;

/// Extensions on nullable generic objects `T?`.
///
/// Provides utilities to validate the existence of a value dynamically.
extension OnNullableObject<T> on T? {
  /// Asserts that this object is not null, returning it as a non-nullable [T].
  ///
  /// If the object is null, it evaluates and throws the [Exception] generated by the [exceptionProducer] callback.
  /// The [exceptionProducer] is evaluated lazily, meaning the exception is only instantiated
  /// if a null value is actually encountered, avoiding unnecessary overhead.
  ///
  /// This is particularly useful for maintaining fluid method chains or expression-based returns
  /// (such as retrieving dependencies from a registry map) without breaking the pipeline
  /// for imperative null checks.
  ///
  /// Example:
  /// ```dart
  /// final dependency = registryMap[key].assertNotNull(
  ///   () => Exception("Registry doesn't have a registration for $key"),
  /// );
  /// ```
  T assertNotNull(Exception Function() exceptionProducer) =>
      this ?? (throw exceptionProducer());
}
