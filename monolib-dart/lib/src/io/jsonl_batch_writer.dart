import 'dart:io';

import 'package:monolib_dart/jsonl.dart';
import 'package:monolib_dart/monolib_dart.dart';

/// A buffered writer that combines a [Batcher] and an [IOSink] to write items
/// to a JSON Lines (JSONL) file in batches.
///
/// [JsonlBatchWriter] accepts items synchronously via [add], buffers them in
/// memory using a [Batcher], and periodically flushes them as JSONL lines to
/// the target [File] using [jsonlEncodeAsync]. The underlying [IOSink] is
/// opened lazily on the first flush.
///
/// Example:
/// ```dart
/// final writer = JsonlBatchWriter<Map<String, Object>>(
///   file: File('logs.jsonl'),
///   maxBatchSize: 50,
///   maxDuration: const Duration(seconds: 1),
/// );
///
/// writer.add({'event': 'app_start', 'timestamp': DateTime.now().toIso8601String()});
/// writer.add({'event': 'login', 'userId': 123});
///
/// await writer.dispose();
/// ```
class JsonlBatchWriter<T> {
  final File _file;
  IOSink? _sink;
  late final Batcher<T> _batcher;

  /// Creates a [JsonlBatchWriter] that lazily appends to the provided [File].
  ///
  /// The writer will flush to disk whenever the internal buffer reaches
  /// [maxBatchSize] items, or if [maxDuration] elapses since the first item
  /// in the current batch was added.
  ///
  /// - [file]: The target [File] to write batched JSONL data into.
  /// - [maxBatchSize]: The maximum number of items to buffer before triggering a write.
  /// - [maxDuration]: The maximum time to wait before flushing an incomplete batch.
  /// - [onError]: A callback invoked if serialization or file writing fails with the
  ///   caught error and stack trace. If [onError] is omitted, errors are printed
  ///   to standard error.
  JsonlBatchWriter({
    required File file,
    int? maxBatchSize = 100,
    Duration? maxDuration = const Duration(milliseconds: 100),
    void Function(Object error, StackTrace stackTrace)? onError,
  }) : _file = file {
    _batcher = Batcher<T>(
      maxBatchSize: maxBatchSize,
      maxDuration: maxDuration,
      onBatch: (List<T> items) async {
        try {
          _sink ??= _file.openWrite(mode: FileMode.writeOnlyAppend);

          await jsonlEncodeAsync(items: items, sink: _sink!);
          await _sink!.flush();
        } catch (e, st) {
          if (onError != null) {
            onError(e, st);
          } else {
            stderr.writeln('JsonlBatchWriter error: $e\n$st');
          }
        }
      },
    );
  }

  /// Adds an [item] to the internal buffer to be later written to the file.
  ///
  /// This operation is fully synchronous and merely adds the object to an in-memory
  /// array via the internal [Batcher]. It avoids blocking the caller's execution.
  void add(T item) => _batcher.add(item);

  /// Flushes any pending items to disk and safely closes the file handle.
  ///
  /// This asynchronous method explicitly waits for any currently executing
  /// batches to finish, writes remaining buffered data to the [IOSink],
  /// and terminates the writer.
  ///
  /// - [onSinkCloseError]: If provided, errors generated by [IOSink.close] (which can
  ///   occur if the file is abruptly deleted or modified elsewhere) will be passed
  ///   to it. Otherwise, the error is allowed to propagate naturally.
  Future<void> dispose({Function? onSinkCloseError}) async {
    await _batcher.dispose();

    final sink = _sink;
    if (sink == null) {
      return;
    }

    switch (onSinkCloseError) {
      case null:
        await sink.close();
      case void Function(Object, StackTrace) handleExceptionAndStacktrace:
        try {
          await sink.close();
        } catch (e, st) {
          handleExceptionAndStacktrace(e, st);
        }
      case void Function(Object) handleException:
        try {
          await sink.close();
        } catch (e) {
          handleException(e);
        }
      default:
        try {
          await sink.close();
        } catch (e, st) {
          // If the user provided a function with an invalid signature,
          // we fall back to calling it dynamically to fail fast or succeed
          // if it was broadly typed.
          (onSinkCloseError as dynamic)(e, st);
        }
    }
  }
}
