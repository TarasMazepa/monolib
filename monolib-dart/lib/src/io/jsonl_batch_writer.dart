import 'dart:io';

import 'package:monolib_dart/jsonl.dart';
import 'package:monolib_dart/monolib_dart.dart';

/// A utility that combines [Batcher] and an [IOSink] to efficiently
/// write high-frequency data to a JSONL file in batches.
///
/// In real-world applications (such as analytics tracking, request logging, or event sourcing),
/// emitting individual events synchronously to disk can introduce significant I/O latency and
/// disk wear. [JsonlBatchWriter] solves this by acting as a decoupling layer: it accepts
/// items synchronously via [add], buffers them in memory using a [Batcher], and periodically
/// flushes them as batched JSON Lines (JSONL) to the underlying file via asynchronous chunks.
///
/// Under the hood, this delegates serialization to [jsonlEncodeAsync] and automatically
/// manages the lifecycle of the internal [IOSink], lazily opening it only upon the first
/// flush operation.
///
/// Example:
/// ```dart
/// final writer = JsonlBatchWriter<Map<String, Object>>(
///   file: File('logs.jsonl'),
///   maxBatchSize: 50,
///   maxDuration: const Duration(seconds: 1),
/// );
///
/// // This is fast and synchronous.
/// writer.add({'event': 'app_start', 'timestamp': DateTime.now().toIso8601String()});
/// writer.add({'event': 'login', 'userId': 123});
///
/// // Shut down the writer gracefully, ensuring pending items are written to disk.
/// await writer.dispose();
/// ```
class JsonlBatchWriter<T> {
  final File _file;
  IOSink? _sink;
  late final Batcher<T> _batcher;

  /// Creates a [JsonlBatchWriter] that lazily appends to the provided [file].
  ///
  /// The writer will flush to disk whenever the internal buffer reaches
  /// [maxBatchSize] items, or if [maxDuration] elapses since the first item
  /// in the current batch was added.
  ///
  /// If serialization or file writing fails, [onError] is called with the
  /// caught error and stack trace. If [onError] is omitted, errors are printed
  /// to `stderr`.
  JsonlBatchWriter({
    required File file,
    int? maxBatchSize = 100,
    Duration? maxDuration = const Duration(milliseconds: 100),
    void Function(Object error, StackTrace stackTrace)? onError,
  }) : _file = file {
    _batcher = Batcher<T>(
      maxBatchSize: maxBatchSize,
      maxDuration: maxDuration,
      onBatch: (List<T> items) async {
        try {
          _sink ??= _file.openWrite(mode: FileMode.writeOnlyAppend);

          await jsonlEncodeAsync(items: items, sink: _sink!);
          await _sink!.flush();
        } catch (e, st) {
          if (onError != null) {
            onError(e, st);
          } else {
            stderr.writeln('JsonlBatchWriter error: $e\n$st');
          }
        }
      },
    );
  }

  /// Adds an [item] to the internal buffer to be later written to the file.
  ///
  /// This operation is fully synchronous and merely adds the object to an in-memory
  /// array via the internal [Batcher]. It avoids blocking the caller's execution.
  void add(T item) => _batcher.add(item);

  /// Flushes any pending items to disk and safely closes the file handle.
  ///
  /// This asynchronous method explicitly waits for any currently executing
  /// batches to finish, writes remaining buffered data to the [IOSink],
  /// and terminates the writer.
  ///
  /// Safe disposal is guaranteed: errors generated by [IOSink.close] (which can
  /// occur if the file is abruptly deleted or modified elsewhere) are silently
  /// caught and ignored to prevent unhandled exceptions during teardown.
  Future<void> dispose() async {
    await _batcher.dispose();
    try {
      await _sink?.close();
    } catch (_) {
      // Ignore errors when closing, as they might stem from the sink
      // already failing during a write operation.
    }
  }
}
